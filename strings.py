"""
strings.py - all interface texts in Arabic and English.

tr('key', name=value) returns the text in the active language.  The text is
returned *logically* (as typed); ALabel shapes / reorders Arabic when drawing.
"""

LANG = 'ar'


def set_lang(lang):
    global LANG
    LANG = lang if lang in ('ar', 'en') else 'ar'


def tr(key, **kw):
    entry = STR.get(key)
    if entry is None:
        return key
    text = entry.get(LANG) or entry.get('en') or key
    if kw:
        try:
            return text.format(**kw)
        except (KeyError, IndexError, ValueError):
            return text
    return text


